/** Only for system-generated feedback; never apply to user content. */
export function zhMessage(value: string): string {
  if (Object.hasOwn(messages, value)) return messages[value];
  const providerKey = value.match(/^(Ollama|OpenAI|DeepSeek|Gemini|OpenRouter) API key not configured$/);
  if (providerKey) return `尚未配置 ${providerKey[1]} API 密钥。`;
  const providerModels = value.match(/^Failed to fetch (Ollama|OpenAI|DeepSeek|Gemini|OpenRouter) models$/);
  if (providerModels) return `获取 ${providerModels[1]} 模型列表失败。`;
  const required = value.match(/^(.+?) is required\.?$/);
  if (required && Object.hasOwn(labels, required[1])) return `请填写${zhLabel(required[1])}。`;
  const small = value.match(/^Too small: expected string to have >=(\d+) characters$/);
  if (small) return `请至少输入 ${small[1]} 个字符。`;
  return value;
}
